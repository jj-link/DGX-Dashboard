#!/usr/bin/env bash
# Run aider's MULTI-TURN polyglot benchmark against the model currently
# served on the SPARK (GB10, gx10-a6c7.lan:8000). Spark counterpart of
# run_aider_local.sh — replaces the old run_aider.sh, which was broken
# (streamed -> aider/LiteLLM hung; no venv/path handling).
#
# benchmark.py itself runs on THIS box; only the LLM calls go to the spark.
# Carries the three fixes proven in run_aider_local.sh:
#   1. Auto-detect the served model id from the spark's /v1/models
#      (spark-serve/models.env's assumed alias may not match the actual id).
#   2. streaming:TRUE via a generated --read-model-settings YAML. The
#      earlier "hang" was misdiagnosed slowness: streaming:false made the
#      client wait silently for a multi-thousand-second non-streamed
#      response and hit LiteLLM's request timeout -> retry death loop.
#      streaming:true keeps tokens flowing (reasoning chunks count as
#      activity), so there is no timeout to hit. Verified end-to-end.
#      max_tokens 32768 (8192 truncates reasoning models and floors scores).
#   3. Explicit venv python + PYTHONPATH (benchmark.py's shebang resolves to
#      system python w/o GitPython; the editable aider install's /mnt/c path
#      doesn't resolve from /home/workbench).
#
# The desired model must already be served on the spark (use
# spark-serve/swap.sh <alias> first). This runs whatever is live.
#
# Usage: ./run_aider_spark.sh [--num-tests N] [--languages L] [--tries N]
set -euo pipefail

NUM_TESTS="${NUM_TESTS:--1}"          # -1 = all
LANGS="${LANGS:-python}"              # python = 34 problems
TRIES="${TRIES:-2}"                   # aider default (multi-turn repair)
THREADS="${THREADS:-1}"
EDIT_FORMAT="${EDIT_FORMAT:-whole}"
MAX_TOKENS="${MAX_TOKENS:-32768}"
BASE="${OPENAI_API_BASE:-http://gx10-a6c7.lan:8000/v1}"

while [ $# -gt 0 ]; do
  case "$1" in
    --num-tests) NUM_TESTS="$2"; shift 2 ;;
    --languages) LANGS="$2"; shift 2 ;;
    --tries) TRIES="$2"; shift 2 ;;
    --threads) THREADS="$2"; shift 2 ;;
    --edit-format) EDIT_FORMAT="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 1 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# 1. Auto-detect the actually-served model id on the spark.
SERVE_NAME=$(curl -fsS --max-time 5 "${BASE%/v1}/v1/models" \
  | grep -o '"id":"[^"]*"' | head -1 | cut -d'"' -f4 || true)
if [ -z "$SERVE_NAME" ]; then
  echo "[aider-spark] FATAL: no model served at $BASE (swap one in first)" >&2
  exit 2
fi

# 2. Generate the model-settings YAML with streaming:true.
SETTINGS="${SCRIPT_DIR}/spark-serve/aider-model-settings.spark.yml"
mkdir -p "${SCRIPT_DIR}/spark-serve"
cat > "$SETTINGS" <<YAML
# AUTO-GENERATED by run_aider_spark.sh for the live spark model.
# streaming:true — keeps tokens flowing so the client never hits a
# request timeout (the streaming:false retry-loop was the real failure).
- name: openai/${SERVE_NAME}
  edit_format: ${EDIT_FORMAT}
  use_repo_map: false
  send_undo_reply: false
  examples_as_sys_msg: true
  streaming: true
  extra_params:
    max_tokens: ${MAX_TOKENS}
    temperature: 0.0
YAML

cd "${SCRIPT_DIR}/aider"
# 3. Explicit venv python + PYTHONPATH (see header).
VENV_PY="${SCRIPT_DIR}/aider/.venv/bin/python"
[ -x "$VENV_PY" ] || { echo "[aider-spark] FATAL: venv python missing: $VENV_PY" >&2; exit 2; }
export PYTHONPATH="${SCRIPT_DIR}/aider:${SCRIPT_DIR}/aider/benchmark${PYTHONPATH:+:$PYTHONPATH}"

RUN_NAME="${SERVE_NAME//[^A-Za-z0-9]/_}-aider-spark-$(date +%Y%m%d-%H%M%S)"
echo "[aider-spark] served=$SERVE_NAME base=$BASE langs=$LANGS num=$NUM_TESTS threads=$THREADS"
echo "[aider-spark] settings=$SETTINGS (streaming=false, max_tokens=$MAX_TOKENS)"
echo "[aider-spark] run=$RUN_NAME"

AIDER_DOCKER=1 \
OPENAI_API_BASE="$BASE" \
OPENAI_API_KEY=dummy \
AIDER_BENCHMARK_DIR=tmp.benchmarks \
  "$VENV_PY" benchmark/benchmark.py "$RUN_NAME" \
    --model "openai/${SERVE_NAME}" \
    --read-model-settings "$SETTINGS" \
    --edit-format "$EDIT_FORMAT" \
    --threads "$THREADS" \
    --languages "$LANGS" \
    --num-tests "$NUM_TESTS" \
    --tries "$TRIES" \
    --new \
    --exercises-dir polyglot-benchmark

LATEST_DIR=$(ls -td tmp.benchmarks/*--"$RUN_NAME" 2>/dev/null | head -1)
if [ -n "$LATEST_DIR" ]; then
  "$VENV_PY" benchmark/benchmark.py --stats "$LATEST_DIR" > "$LATEST_DIR/_stats.yml" 2>&1 || true
  echo "[aider-spark] stats -> $LATEST_DIR/_stats.yml"

  # Serving-config snapshot (the spark vLLM container 'vllm' is remote, so
  # inspect it over SSH). Makes each result self-describing for comparisons.
  CARGS=$(ssh -o BatchMode=yes "$SPARK_HOST" "docker inspect vllm --format '{{join .Args \" \"}}'" 2>/dev/null)
  CIMG=$(ssh -o BatchMode=yes "$SPARK_HOST" "docker inspect vllm --format '{{.Config.Image}}'" 2>/dev/null)
  KVTOK=$(ssh -o BatchMode=yes "$SPARK_HOST" "docker logs vllm 2>&1 | grep -oE 'GPU KV cache size: [0-9,]+ tokens' | tail -1 | grep -oE '[0-9,]+'" 2>/dev/null | tr -d ',')
  field() { echo "$CARGS" | grep -oE -- "$1 [^ ]+" | head -1 | awk '{print $2}'; }
  {
    echo "# auto-generated serving + benchmark config snapshot"
    echo "run_name: $RUN_NAME"
    echo "timestamp: $(date -Is)"
    echo "served_name: $SERVE_NAME"
    echo "endpoint: $BASE"
    echo "machine: spark-gb10"
    echo "# --- aider/benchmark side ---"
    echo "edit_format: $EDIT_FORMAT"
    echo "max_tokens: $MAX_TOKENS"
    echo "threads: $THREADS"
    echo "streaming: true"
    echo "tries: $TRIES"
    echo "languages: $LANGS"
    echo "num_tests: $NUM_TESTS"
    echo "# --- vLLM serving side (from remote container) ---"
    echo "image: ${CIMG:-?}"
    echo "model_repo: $(echo "$CARGS" | sed -E 's/^serve ([^ ]+).*/\1/')"
    echo "kv_cache_dtype: $(field --kv-cache-dtype)"
    echo "max_num_seqs: $(field --max-num-seqs)"
    echo "max_model_len: $(field --max-model-len)"
    echo "gpu_memory_utilization: $(field --gpu-memory-utilization)"
    echo "mamba_ssm_cache_dtype: $(field --mamba-ssm-cache-dtype)"
    echo "kv_cache_tokens: ${KVTOK:-?}"
    echo "vllm_serve_command: \"$CARGS\""
  } > "$LATEST_DIR/_serving.yml"
  echo "[aider-spark] serving config -> $LATEST_DIR/_serving.yml"
fi
