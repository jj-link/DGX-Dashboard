#!/usr/bin/env bash
# Run aider's MULTI-TURN polyglot benchmark against the model currently
# served on THIS box (RTX 6000, localhost:8000) — the local counterpart of
# run_aider_spark.sh (which is hardwired to spark/gx10-a6c7.lan).
#
# Fixes the two known blockers:
#   1. Machine: targets http://localhost:8000 and AUTO-DETECTS the served
#      model id from /v1/models (local-serve/models.env's assumed name
#      e.g. qwen36-27b-fp8 does NOT match the server's actual id
#      e.g. Qwen3.6-27B — trusting it would send the wrong model).
#   2. streaming:TRUE via a generated --read-model-settings YAML. The
#      earlier "hang" turned out to be misdiagnosed slowness — streaming:false
#      made the client wait silently for a multi-thousand-second non-streamed
#      response and hit LiteLLM's request timeout -> retry death loop. Real
#      streaming requires both this setting AND benchmark.py:827 stream=True
#      (the AND-gate in base_coder.py:424). Verified end-to-end.
#      max_tokens is 32768 (8192 truncates reasoning models and floors scores).
#
# Usage: ./run_aider_local.sh [--num-tests N] [--languages L] [--tries N]
set -euo pipefail

NUM_TESTS="${NUM_TESTS:--1}"          # -1 = all
LANGS="${LANGS:-python}"              # python = 34 problems
TRIES="${TRIES:-2}"                   # aider default (multi-turn repair)
THREADS="${THREADS:-1}"
EDIT_FORMAT="${EDIT_FORMAT:-whole}"
# 49152, not 65536: in 2-turn aider, turn-1's full output feeds turn-2's input,
# so input+output must stay < max_model_len (131072). 2*49152 + ~5k base ≈ 103k
# (safe); 65536 overflowed (turn-2 input + 65536 output > 131072 -> vLLM 400).
MAX_TOKENS="${MAX_TOKENS:-49152}"
BASE="${OPENAI_API_BASE:-http://localhost:8000/v1}"

while [ $# -gt 0 ]; do
  case "$1" in
    --num-tests) NUM_TESTS="$2"; shift 2 ;;
    --languages) LANGS="$2"; shift 2 ;;
    --tries) TRIES="$2"; shift 2 ;;
    --threads) THREADS="$2"; shift 2 ;;
    --edit-format) EDIT_FORMAT="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 1 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Auto-detect the actually-served model id (blocker 1).
SERVE_NAME=$(curl -fsS --max-time 5 "${BASE%/v1}/v1/models" \
  | grep -o '"id":"[^"]*"' | head -1 | cut -d'"' -f4 || true)
if [ -z "$SERVE_NAME" ]; then
  echo "[aider-local] FATAL: no model served at $BASE" >&2
  exit 2
fi

# Generate the model-settings YAML with streaming:true.
SETTINGS="${SCRIPT_DIR}/local-serve/aider-model-settings.local.yml"
mkdir -p "${SCRIPT_DIR}/local-serve"
cat > "$SETTINGS" <<YAML
# AUTO-GENERATED by run_aider_local.sh for the live local model.
# streaming:true — keeps tokens flowing so the client never hits a request
# timeout. Requires benchmark.py:827 stream=True for it to actually engage.
- name: openai/${SERVE_NAME}
  edit_format: ${EDIT_FORMAT}
  use_repo_map: false
  send_undo_reply: false
  examples_as_sys_msg: true
  streaming: true
  extra_params:
    max_tokens: ${MAX_TOKENS}
    temperature: 0.0
YAML

cd "${SCRIPT_DIR}/aider"
# Invoke the venv interpreter explicitly. benchmark.py's shebang is
# `#!/usr/bin/env python3`, which resolves to SYSTEM python (no GitPython)
# even after `source .venv/bin/activate` — so call .venv/bin/python directly.
VENV_PY="${SCRIPT_DIR}/aider/.venv/bin/python"
[ -x "$VENV_PY" ] || { echo "[aider-local] FATAL: venv python missing: $VENV_PY" >&2; exit 2; }
# The `aider-chat` editable install registers a /mnt/c/... path that doesn't
# resolve from /home/workbench/... (same files, different WSL mount), so
# `import aider` fails. Put the repo root + benchmark/ on PYTHONPATH so the
# aider package and benchmark's sibling modules (prompts, plots) all import.
export PYTHONPATH="${SCRIPT_DIR}/aider:${SCRIPT_DIR}/aider/benchmark${PYTHONPATH:+:$PYTHONPATH}"

RUN_NAME="${SERVE_NAME//[^A-Za-z0-9]/_}-aider-local-$(date +%Y%m%d-%H%M%S)"
echo "[aider-local] served=$SERVE_NAME base=$BASE langs=$LANGS num=$NUM_TESTS"
echo "[aider-local] settings=$SETTINGS (streaming=true, max_tokens=$MAX_TOKENS)"
echo "[aider-local] run=$RUN_NAME"

AIDER_DOCKER=1 \
OPENAI_API_BASE="$BASE" \
OPENAI_API_KEY=dummy \
AIDER_BENCHMARK_DIR=tmp.benchmarks \
  "$VENV_PY" benchmark/benchmark.py "$RUN_NAME" \
    --model "openai/${SERVE_NAME}" \
    --read-model-settings "$SETTINGS" \
    --edit-format "$EDIT_FORMAT" \
    --threads "$THREADS" \
    --languages "$LANGS" \
    --num-tests "$NUM_TESTS" \
    --tries "$TRIES" \
    --new \
    --exercises-dir polyglot-benchmark

LATEST_DIR=$(ls -td tmp.benchmarks/*--"$RUN_NAME" 2>/dev/null | head -1)
if [ -n "$LATEST_DIR" ]; then
  "$VENV_PY" benchmark/benchmark.py --stats "$LATEST_DIR" > "$LATEST_DIR/_stats.yml" 2>&1 || true
  echo "[aider-local] stats -> $LATEST_DIR/_stats.yml"

  # Serving-config snapshot so every result is self-describing (e.g. fp8 vs
  # 16-bit KV comparisons). Pull the actual vLLM serving args from the live
  # container; copy its startup log; record the aider-side params too.
  CN=$(docker ps --format '{{.Names}}' | grep '^vllm-serve_' | head -1)
  CARGS=$(docker inspect "$CN" --format '{{join .Args " "}}' 2>/dev/null)
  CIMG=$(docker inspect "$CN" --format '{{.Config.Image}}' 2>/dev/null)
  field() { echo "$CARGS" | grep -oE -- "$1 [^ ]+" | head -1 | awk '{print $2}'; }
  VLOG=$(ls -t /tmp/local-vllm-logs/*-*.log 2>/dev/null | head -1)
  KVTOK=$(grep -oE 'GPU KV cache size: [0-9,]+ tokens' "$VLOG" 2>/dev/null | tail -1 | grep -oE '[0-9,]+' | tr -d ',')
  {
    echo "# auto-generated serving + benchmark config snapshot"
    echo "run_name: $RUN_NAME"
    echo "timestamp: $(date -Is)"
    echo "served_name: $SERVE_NAME"
    echo "endpoint: $BASE"
    echo "machine: local-rtx6000"
    echo "# --- aider/benchmark side ---"
    echo "edit_format: $EDIT_FORMAT"
    echo "max_tokens: $MAX_TOKENS"
    echo "threads: $THREADS"
    echo "streaming: true"
    echo "tries: $TRIES"
    echo "languages: $LANGS"
    echo "num_tests: $NUM_TESTS"
    echo "# --- vLLM serving side (from live container) ---"
    echo "image: ${CIMG:-?}"
    echo "model_repo: $(echo "$CARGS" | sed -E 's/^serve ([^ ]+).*/\1/')"
    echo "kv_cache_dtype: $(field --kv-cache-dtype)"
    echo "max_num_seqs: $(field --max-num-seqs)"
    echo "max_model_len: $(field --max-model-len)"
    echo "gpu_memory_utilization: $(field --gpu-memory-utilization)"
    echo "mamba_ssm_cache_dtype: $(field --mamba-ssm-cache-dtype)"
    echo "kv_cache_tokens: ${KVTOK:-?}"
    echo "vllm_serve_command: \"$CARGS\""
  } > "$LATEST_DIR/_serving.yml"
  [ -n "$VLOG" ] && cp "$VLOG" "$LATEST_DIR/_vllm_startup.log" 2>/dev/null
  echo "[aider-local] serving config -> $LATEST_DIR/_serving.yml"
fi
